"""
load_db.py
==========
Loads the synthetic invoice data and holiday reference table into a SQLite
database so the SQL detection rules can query them.

Inputs  (must exist before running)
-------
  data/raw/invoices.csv   — generated by src/generate_data.py
  data/holidays.csv       — hardcoded Indian national holidays

Output
------
  data/db/invoices.db     — SQLite database with two tables:
                            invoices   (one row per invoice)
                            holidays   (one row per holiday date)

Indexes created
---------------
  idx_invoices_vendor_id      on invoices(vendor_id)
  idx_invoices_invoice_date   on invoices(invoice_date)
  idx_invoices_payment_date   on invoices(payment_date)
  idx_invoices_vendor_date    on invoices(vendor_id, invoice_date)  -- composite
  idx_holidays_date           on holidays(date)

Usage
-----
  python src/load_db.py          (run from project root)

Notes
-----
  - Drops and recreates tables on every run (idempotent).
  - Dates are stored as TEXT in ISO format (YYYY-MM-DD) because SQLite
    has no native DATE type; the SQL rules use date() / julianday() to
    compare them correctly.
"""

import sqlite3
import pandas as pd
from pathlib import Path

# ── Paths: always relative to project root ───────────────────────────────────
ROOT          = Path(__file__).parent.parent
INVOICES_CSV  = ROOT / "data" / "raw" / "invoices.csv"
HOLIDAYS_CSV  = ROOT / "data" / "holidays.csv"
DB_DIR        = ROOT / "data" / "db"
DB_PATH       = DB_DIR / "invoices.db"


def load_invoices(conn: sqlite3.Connection) -> int:
    """
    Read invoices.csv and write to the 'invoices' table.
    Returns the number of rows loaded.
    """
    df = pd.read_csv(INVOICES_CSV)

    # Ensure date columns are stored as ISO strings
    df["invoice_date"] = pd.to_datetime(df["invoice_date"]).dt.strftime("%Y-%m-%d")
    df["payment_date"] = pd.to_datetime(df["payment_date"]).dt.strftime("%Y-%m-%d")

    # Drop and recreate so the script is idempotent
    conn.execute("DROP TABLE IF EXISTS invoices")
    df.to_sql("invoices", conn, index=False, if_exists="replace")

    # Indexes for fast lookups used by the detection rules
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_invoices_vendor_id "
        "ON invoices(vendor_id)"
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_invoices_invoice_date "
        "ON invoices(invoice_date)"
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_invoices_payment_date "
        "ON invoices(payment_date)"
    )
    # Composite index speeds up the duplicate and split-invoice self-joins
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_invoices_vendor_date "
        "ON invoices(vendor_id, invoice_date)"
    )
    conn.commit()
    return len(df)


def load_holidays(conn: sqlite3.Connection) -> int:
    """
    Read holidays.csv and write to the 'holidays' table.
    Returns the number of rows loaded.
    """
    df = pd.read_csv(HOLIDAYS_CSV)
    df["date"] = pd.to_datetime(df["date"]).dt.strftime("%Y-%m-%d")

    conn.execute("DROP TABLE IF EXISTS holidays")
    df.to_sql("holidays", conn, index=False, if_exists="replace")

    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_holidays_date "
        "ON holidays(date)"
    )
    conn.commit()
    return len(df)


def verify(conn: sqlite3.Connection) -> None:
    """Print a quick sanity check of what was loaded."""
    inv_count = conn.execute("SELECT COUNT(*) FROM invoices").fetchone()[0]
    hol_count = conn.execute("SELECT COUNT(*) FROM holidays").fetchone()[0]
    min_date  = conn.execute("SELECT MIN(invoice_date) FROM invoices").fetchone()[0]
    max_date  = conn.execute("SELECT MAX(invoice_date) FROM invoices").fetchone()[0]
    vendors   = conn.execute("SELECT COUNT(DISTINCT vendor_id) FROM invoices").fetchone()[0]

    # List all indexes
    indexes = conn.execute(
        "SELECT name FROM sqlite_master WHERE type='index' ORDER BY name"
    ).fetchall()

    print("\n" + "=" * 55)
    print("LOAD_DB VERIFICATION")
    print("=" * 55)
    print(f"invoices rows loaded   : {inv_count:,}")
    print(f"holidays rows loaded   : {hol_count}")
    print(f"distinct vendors       : {vendors}")
    print(f"invoice date range     : {min_date} to {max_date}")
    print(f"indexes created        : {[r[0] for r in indexes]}")
    print(f"database path          : {DB_PATH}")
    print("=" * 55)


def main():
    DB_DIR.mkdir(parents=True, exist_ok=True)

    print(f"Connecting to {DB_PATH} ...")
    conn = sqlite3.connect(DB_PATH)

    print("Loading invoices ...")
    n_inv = load_invoices(conn)
    print(f"  {n_inv:,} rows written to 'invoices' table.")

    print("Loading holidays ...")
    n_hol = load_holidays(conn)
    print(f"  {n_hol} rows written to 'holidays' table.")

    verify(conn)
    conn.close()
    print("Done.")


if __name__ == "__main__":
    main()
